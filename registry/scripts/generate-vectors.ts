/**
 * Regenerate conformance/vectors.json.
 *
 *     npm run vectors
 *
 * The artifact is committed, and a test compares it against a fresh generation. That is
 * deliberate: the vectors are the interoperability contract, so a change to any encoding rule
 * must show up as a reviewable diff in the file rather than as a silently different expectation.
 */

