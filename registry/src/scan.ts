/**
 * The rules no header can express, and the scanner that finds them.
 *
 * ## Why this file exists
 *
 * The rule table in `conformance/rules.json` classifies every authoring rule by how it is
 * enforced. Eighteen of the twenty-one are enforced by a header the proxy emits, or are
 * publish-time checks the publisher's own checker makes. **Three are not**, and the table says
 * so in the word `scan`: a speculative `<link rel>`, a `<meta http-equiv="refresh">`, and a
 * service-worker registration. No Content-Security-Policy expresses any of them — speculative
 * DNS fires before a policy applies, meta refresh bypasses CSP entirely, and nothing in CSP
 * stops a service worker registering itself.
 *
 * The client's serving surface refuses a document carrying any of the three. **The registry's
 * serving surface did not**, and that is a hole rather than a difference of opinion: the proxy
 * is the surface that serves content it did not publish, so it is exactly the one that cannot
 * rely on the publisher having run a checker first. A peer can publish a site whose index page
 * carries `<link rel="preconnect" href="https://tracker.example/">`, and the proxy would serve
 * it, and the reader's browser would contact the tracker — which is the whole thing VayuWeb
 * exists to prevent, and the exact sentence in the rule's own `why`.
 *
 * ## Why this is a second implementation, and how it is held to the first
 *
 * The client is Rust and the registry is TypeScript, so the detection is written twice. A second
 * copy of a rule is a copy that drifts, and this project has been bitten by that shape enough to
 * have a rule about it. Three things hold the copies together:
 *
 * 1. **The rule text is pinned to the shared definition.** `scan.test.ts` reads
 *    `conformance/rules.json` and asserts that the `scan` class is exactly these three rules and
 *    that each one's `what`, `why` and `fix` are byte-identical to the definition's. The text
 *    here is a copy, and the test is what makes it a checked copy.
 * 2. **The detection is pinned by a conformance suite.** `conformance/vectors.json` carries a
 *    `scan` suite: a document and the rules every implementation must find in it. The client's
 *    doctor and this scanner both answer it, so a difference in judgement is a red test rather
 *    than a difference nobody notices.
 * 3. **The rule ids are pinned to the classification.** The `scan` class in the shared
 *    definition is the list of rules the resolver owes an enforcement for, and a rule added
 *    there without an implementation here fails the same test.
 *
 * ## What is deliberately NOT here
 *
 * The other eighteen rules. A resolver's obligation is the scan class and nothing else: the
 * header-enforced rules are enforced by the header itself, and the publish-time rules (the size
 * ladders, the index document, manifest validity) belong to the publisher's checker, which
 * refuses to publish. Reimplementing them here would be a second implementation of a
 * publish-time gate on the read path, and would put two answers to "does this tree pass?" in
 * circulation.
 */

/** The rules the resolver owes an enforcement for, and the ids the shared definition uses. */
export type ScanRuleId = 'speculative-link' | 'meta-refresh' | 'service-worker';

export interface ScanRule {
  readonly id: ScanRuleId;
  /** What will not work, in one line, in plain language. */
  readonly what: string;
  /** Why VayuWeb restricts it. */
  readonly why: string;
  /** A concrete fix. */
  readonly fix: string;
}

/**
 * The scan class, with the text the shared definition carries.
 *
 * A copy, deliberately: `conformance/rules.json` is generated by the client and is not a runtime
 * dependency of the registry package. `scan.test.ts` holds the copy to the definition.
 */
export const SCAN_RULES: readonly ScanRule[] = [
  {
    id: 'speculative-link',
    what: 'a speculative-loading <link rel>',
    why:
      'dns-prefetch, preconnect, prefetch, preload, prerender and modulepreload all contact ' +
      'another server on the speculation that a reader will click. On VayuWeb they do nothing ' +
      'except leak who is reading.',
    fix: 'remove the tag; the resource loads when it is used.',
  },
  {
    id: 'meta-refresh',
    what: '<meta http-equiv="refresh">',
    why:
      'Auto-redirecting a reader to another address is indistinguishable from open-redirect ' +
      'abuse, so VayuWeb does not honour it.',
    fix: "link to the destination instead, or serve the destination's content directly.",
  },
  {
    id: 'service-worker',
    what: 'service-worker registration',
    why:
      'A service worker keeps running after the reader leaves, which VayuWeb promises never to ' +
      'allow. Registration is blocked, so code depending on one misbehaves.',
    fix: "remove the registration; cache nothing beyond the reader's visit.",
  },
];

/**
 * The `<link rel>` values that contact another server on the reader's behalf.
 *
 * The same six the client names, in the same order.
 */
export const SPECULATIVE_RELS: readonly string[] = [
  'dns-prefetch',
  'preconnect',
  'prefetch',
  'preload',
  'prerender',
  'modulepreload',
];

/** One thing wrong with a document, in the shape a refusal can name. */
export interface ScanFinding {
  readonly rule: ScanRuleId;
  /** The path the document was served at. */
  readonly file: string;
  /** The line the violation is on, 1-based; 0 when the document has no lines to point at. */
  readonly line: number;
  readonly what: string;
  readonly why: string;
  readonly fix: string;
}

/**
 * Split an attribute region into (name, value) pairs, honouring quotes.
 *
 * A faithful port of the client's `attributes`, because the two have to agree on where an
 * attribute ends: a `>` inside a quoted value is part of the value, and a value that runs to the
 * end of the region is a value.
 */
function attributes(region: string): [string, string][] {
  const out: [string, string][] = [];
  let i = 0;
  while (i < region.length) {
    while (i < region.length && /\s/.test(region[i] as string)) i += 1;
    const start = i;
    while (
      i < region.length &&
      region[i] !== '=' &&
      !/\s/.test(region[i] as string) &&
      region[i] !== '>'
    ) {
      i += 1;
    }
    if (start === i) break;
    const name = region.slice(start, i).toLowerCase();
    let value = '';
    if (i < region.length && region[i] === '=') {
      i += 1;
      if (i < region.length && (region[i] === '"' || region[i] === "'")) {
        const quote = region[i];
        i += 1;
        const vstart = i;
        while (i < region.length && region[i] !== quote) i += 1;
        value = region.slice(vstart, Math.min(i, region.length));
        i += 1;
      } else {
        const vstart = i;
        while (i < region.length && !/\s/.test(region[i] as string) && region[i] !== '>') i += 1;
        value = region.slice(vstart, i);
      }
    }
    out.push([name, value]);
  }
  return out;
}

function attributeValue(attrs: [string, string][], name: string): string | undefined {
  const found = attrs.find(([key]) => key === name);
  return found === undefined ? undefined : found[1];
}

/**
 * Walk every tag in an HTML document, yielding (tag name, attribute region, line number).
 *
 * A port of the client's `for_each_tag`. The parts that matter to the scan class: a comment or a
 * doctype is skipped whole (a `<!--` before a `>` must not open a tag), the tag name is
 * lowercased and may not contain whitespace, and an unterminated tag ends the scan rather than
 * running off the end of the document.
 */
function forEachTag(
  html: string,
  visit: (name: string, region: string, line: number) => void,
): void {
  let line = 1;
  let i = 0;
  while (i < html.length) {
    const char = html[i] as string;
    if (char === '\n') {
      line += 1;
      i += 1;
      continue;
    }
    if (char !== '<') {
      i += 1;
      continue;
    }
    if (html.startsWith('<!--', i)) {
      const end = html.indexOf('-->', i);
      if (end === -1) return;
      line += (html.slice(i, i + end).match(/\n/g) ?? []).length;
      i = end + 3;
      continue;
    }
    const tagLine = line;
    const nameStart = i + 1;
    let j = nameStart;
    while (j < html.length && /[A-Za-z0-9-]/.test(html[j] as string)) j += 1;
    const rawName = html.slice(nameStart, j);
    const name = rawName.replace(/^\/+/, '').toLowerCase();
    if (rawName === '' || rawName.startsWith('!') || rawName.startsWith('?')) {
      i += 1;
      continue;
    }
    const attrsStart = j;
    let quote: string | null = null;
    while (j < html.length) {
      const c = html[j] as string;
      if (quote !== null && c === quote) {
        quote = null;
      } else if (quote === null && (c === '"' || c === "'")) {
        quote = c;
      } else if (quote === null && c === '>') {
        break;
      } else if (c === '\n') {
        line += 1;
      }
      j += 1;
    }
    if (j >= html.length) return;
    visit(name, html.slice(attrsStart, j).trim(), tagLine);
    i = j + 1;
  }
}

/** Does this text register a service worker? */
function registersServiceWorker(text: string): boolean {
  return (
    text.includes('navigator.serviceWorker.register') || text.includes('serviceWorker.register(')
  );
}

/**
 * The line the first occurrence of a needle is on, 1-based.
 *
 * One when the needle is absent, which is what the client returns: the two implementations have
 * to agree on a line number, and a line of zero is not a line anybody can be shown.
 */
function lineOfFirst(text: string, needle: string): number {
  const at = text.indexOf(needle);
  if (at === -1) return 1;
  return text.slice(0, at).split('\n').length;
}

/**
 * Scan a document for the scan class.
 *
 * The document is selected by its PATH, exactly as the client's checker selects by extension:
 * `.html` and `.htm` are scanned as markup, `.js` and `.mjs` as script. A path with neither
 * extension is not a document a browser renders, so it carries no scan-class obligation — the
 * client makes the same decision for the same reason.
 *
 * An HTML document is ALSO scanned as script, because an inline `<script>` lives inside it: the
 * service-worker registration is in the page, not in a file beside it.
 */
export function scanDocument(path: string, bytes: Uint8Array): ScanFinding[] {
  const lower = path.toLowerCase();
  const isMarkup = lower.endsWith('.html') || lower.endsWith('.htm');
  const isScript = lower.endsWith('.js') || lower.endsWith('.mjs');
  if (!isMarkup && !isScript) return [];

  const text = new TextDecoder('utf-8', { fatal: false }).decode(bytes);
  const findings: ScanFinding[] = [];
  const rule = (id: ScanRuleId): ScanRule => {
    const found = SCAN_RULES.find((candidate) => candidate.id === id);
    if (found === undefined) throw new Error(`the scan class has no rule ${id}`);
    return found;
  };

  if (isMarkup) {
    forEachTag(text, (name, region, line) => {
      if (name === 'link') {
        const attrs = attributes(region);
        const rel = attributeValue(attrs, 'rel')?.toLowerCase();
        if (rel !== undefined && SPECULATIVE_RELS.includes(rel)) {
          const r = rule('speculative-link');
          findings.push({ rule: r.id, file: path, line, what: r.what, why: r.why, fix: r.fix });
        }
      }
      if (name === 'meta') {
        const attrs = attributes(region);
        const equiv = attributeValue(attrs, 'http-equiv')?.toLowerCase();
        if (equiv === 'refresh') {
          const r = rule('meta-refresh');
          findings.push({ rule: r.id, file: path, line, what: r.what, why: r.why, fix: r.fix });
        }
      }
    });
  }

  if (isMarkup || isScript) {
    if (registersServiceWorker(text)) {
      const r = rule('service-worker');
      findings.push({
        rule: r.id,
        file: path,
        // The registration call, not a feature-detection mention earlier in the file.
        line: Math.max(
          lineOfFirst(text, 'serviceWorker.register'),
          lineOfFirst(text, 'serviceWorker'),
        ),
        what: r.what,
        why: r.why,
        fix: r.fix,
      });
    }
  }

  findings.sort((a, b) => a.line - b.line);
  return findings;
}
